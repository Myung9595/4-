def dyn(first, add):
    """Prefix the first token of a bar with dynamics/markups."""
    toks = first.split(" ", 1)
    head = toks[0]
    if "=" in head:
        a, b = head.split("=", 1)
        head = a + add + "=" + b
    else:
        head = head + add
    return head + ((" " + toks[1]) if len(toks) > 1 else "")


